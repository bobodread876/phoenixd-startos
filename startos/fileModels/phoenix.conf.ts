import { FileHelper, matches } from '@start9labs/start-sdk'

const { object, string, literals, number, boolean } = matches

// Default values
const defaults = {
  chain: 'mainnet' as const,
  'auto-liquidity': '2m' as '2m' | 'off' | '5m' | '10m',
  'http-bind-ip': '0.0.0.0',
  'http-bind-port': 9740,
}

// Validation schema
const shape = object({
  // Network
  chain: literals('mainnet', 'testnet').onMismatch(defaults.chain),

  // Liquidity
  'auto-liquidity': literals('off', '2m', '5m', '10m').onMismatch(
    defaults['auto-liquidity'],
  ),
  'max-absolute-fee': number.optional(),
  'max-fee-credit': literals('off', '50k', '125k', '250k').optional(),

  // HTTP API
  'http-bind-ip': string.onMismatch(defaults['http-bind-ip']),
  'http-bind-port': number.onMismatch(defaults['http-bind-port']),
  'http-password': string.optional(),
  'http-password-limited-access': string.optional(),

  // Integrations
  webhook: string.optional(),
  'webhook-secret': string.optional(),
  'mempool-space-url': string.optional(),
})

type PhoenixConf = typeof shape._TYPE

/**
 * Parse phoenixd config file (key=value format) into typed object
 */
function fromPhoenixConf(str: string): PhoenixConf {
  const conf: any = {}

  for (const line of str.split('\n')) {
    const trimmed = line.trim()

    // Skip empty lines and comments
    if (!trimmed || trimmed.startsWith('#')) continue

    const [key, ...valueParts] = trimmed.split('=')
    if (!key || valueParts.length === 0) continue

    const value = valueParts.join('=').trim()

    // Type coercion
    if (key === 'http-bind-port') {
      conf[key] = parseInt(value, 10)
    } else if (key === 'max-absolute-fee') {
      conf[key] = parseInt(value, 10)
    } else {
      conf[key] = value
    }
  }

  return conf
}

/**
 * Serialize typed object back to phoenixd config format
 */
function toPhoenixConf(conf: PhoenixConf): string {
  let output = '# phoenixd configuration\n'
  output += '# Generated by StartOS\n\n'

  // Network
  output += '# Network\n'
  output += `chain=${conf.chain}\n\n`

  // HTTP API
  output += '# HTTP API\n'
  output += `http-bind-ip=${conf['http-bind-ip']}\n`
  output += `http-bind-port=${conf['http-bind-port']}\n`
  if (conf['http-password']) {
    output += `http-password=${conf['http-password']}\n`
  }
  if (conf['http-password-limited-access']) {
    output += `http-password-limited-access=${conf['http-password-limited-access']}\n`
  }
  output += '\n'

  // Liquidity
  output += '# Liquidity Management\n'
  output += `auto-liquidity=${conf['auto-liquidity']}\n`
  if (conf['max-absolute-fee'] !== undefined) {
    output += `max-absolute-fee=${conf['max-absolute-fee']}\n`
  }
  if (conf['max-fee-credit'] !== undefined) {
    output += `max-fee-credit=${conf['max-fee-credit']}\n`
  }
  output += '\n'

  // Integrations
  if (conf.webhook || conf['webhook-secret'] || conf['mempool-space-url']) {
    output += '# Integrations\n'
    if (conf['webhook-secret']) {
      output += `webhook-secret=${conf['webhook-secret']}\n`
    }
    if (conf.webhook) {
      output += `webhook=${conf.webhook}\n`
    }
    if (conf['mempool-space-url']) {
      output += `mempool-space-url=${conf['mempool-space-url']}\n`
    }
  }

  return output
}

export const phoenixConfFile = FileHelper.raw(
  {
    volumeId: 'main',
    subpath: 'phoenix.conf',
  },
  (obj: typeof shape._TYPE) => toPhoenixConf(obj),
  (str) => fromPhoenixConf(str),
  (obj) => shape.withMismatch(() => shape.unsafeCast({})).unsafeCast(obj),
)

export { defaults as phoenixConfDefaults }
export type { PhoenixConf }
